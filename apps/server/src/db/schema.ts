import type {
  ActivityChange,
  ActivityKind,
  Color,
  CommentBody,
  Description,
  Priority,
  PriorityNames,
  StatusCategory,
  TagIconName,
  WorkspaceRole,
} from '@throw/shared';
import { sql } from 'drizzle-orm';
import {
  type AnyPgColumn,
  boolean,
  index,
  integer,
  jsonb,
  pgTable,
  primaryKey,
  smallint,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';

const createdAt = () => timestamp({ withTimezone: true }).notNull().defaultNow();
const updatedAt = () =>
  timestamp({ withTimezone: true })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date());

// Better Auth tables. Field names must match what Better Auth expects.

export const user = pgTable('user', {
  id: text().primaryKey(),
  name: text().notNull(),
  email: text().notNull().unique(),
  emailVerified: boolean().notNull().default(false),
  image: text(),
  role: text().notNull().default('user'),
  lastLoginAt: timestamp({ withTimezone: true }),
  createdAt: createdAt(),
  updatedAt: updatedAt(),
});

export const session = pgTable(
  'session',
  {
    id: text().primaryKey(),
    expiresAt: timestamp({ withTimezone: true }).notNull(),
    token: text().notNull().unique(),
    ipAddress: text(),
    userAgent: text(),
    userId: text()
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [index().on(table.userId)],
);

export const account = pgTable(
  'account',
  {
    id: text().primaryKey(),
    accountId: text().notNull(),
    providerId: text().notNull(),
    userId: text()
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    accessToken: text(),
    refreshToken: text(),
    idToken: text(),
    accessTokenExpiresAt: timestamp({ withTimezone: true }),
    refreshTokenExpiresAt: timestamp({ withTimezone: true }),
    scope: text(),
    password: text(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [index().on(table.userId)],
);

export const verification = pgTable(
  'verification',
  {
    id: text().primaryKey(),
    identifier: text().notNull(),
    value: text().notNull(),
    expiresAt: timestamp({ withTimezone: true }).notNull(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [index().on(table.identifier)],
);

// App tables. Rows belong to a workspace, and a user reaches them through membership, never
// through a user id of their own (docs/spec.md).

export const workspaces = pgTable('workspaces', {
  /** UUIDv7 generated by the client so workspaces can be created offline. */
  id: uuid().primaryKey(),
  name: text().notNull(),
  /** Fractional index among the workspaces (see `positionBetween`). */
  position: text().notNull(),
  createdAt: createdAt(),
  updatedAt: updatedAt(),
});

export const workspaceMembers = pgTable(
  'workspace_members',
  {
    workspaceId: uuid()
      .notNull()
      .references(() => workspaces.id, { onDelete: 'cascade' }),
    userId: text()
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    role: text().$type<WorkspaceRole>().notNull(),
    createdAt: createdAt(),
  },
  (table) => [primaryKey({ columns: [table.workspaceId, table.userId] }), index().on(table.userId)],
);

export const projects = pgTable(
  'projects',
  {
    id: uuid().primaryKey(),
    workspaceId: uuid()
      .notNull()
      .references(() => workspaces.id, { onDelete: 'cascade' }),
    name: text().notNull(),
    color: text().notNull(),
    icon: text(),
    /** Fractional index among the workspace's projects. */
    position: text().notNull(),
    /** The prefix of task identifiers, unique in the workspace counting the trash (ADR 0007). */
    key: text().notNull(),
    /** The last task number handed out. Never synced. */
    taskCounter: integer().notNull().default(0),
    /** The five ranks' names, in rank order. An empty name shows the default. */
    priorityNames: jsonb().$type<PriorityNames>().notNull().default(sql`'["","","","",""]'::jsonb`),
    /** Set while the project is in the trash. */
    deletedAt: timestamp({ withTimezone: true }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [index().on(table.workspaceId), uniqueIndex().on(table.workspaceId, table.key)],
);

// Rows below a project carry its workspace for membership filters (ADR 0004) and its project
// so that project membership can be added later without changing a table. The server sets
// both from the parent row.

export const statuses = pgTable(
  'statuses',
  {
    id: uuid().primaryKey(),
    workspaceId: uuid()
      .notNull()
      .references(() => workspaces.id, { onDelete: 'cascade' }),
    projectId: uuid()
      .notNull()
      .references(() => projects.id, { onDelete: 'cascade' }),
    name: text().notNull(),
    category: text().$type<StatusCategory>().notNull(),
    /** Fractional index among the project's statuses of the same category. */
    position: text().notNull(),
    isDefault: boolean().notNull(),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [
    index().on(table.workspaceId),
    index().on(table.projectId),
    // At most one default per category; the routes keep it at exactly one.
    uniqueIndex().on(table.projectId, table.category).where(sql`${table.isDefault}`),
  ],
);

/** Project-owned, unbounded tag tree (Catch ADR 0016 adapted in data-model.md). */
export const tags = pgTable(
  'tags',
  {
    id: uuid().primaryKey(),
    workspaceId: uuid()
      .notNull()
      .references(() => workspaces.id, { onDelete: 'cascade' }),
    projectId: uuid()
      .notNull()
      .references(() => projects.id, { onDelete: 'cascade' }),
    name: text().notNull(),
    parentId: uuid().references((): AnyPgColumn => tags.id, { onDelete: 'cascade' }),
    icon: text().$type<TagIconName>(),
    color: text().$type<Color>(),
  },
  (table) => [
    index().on(table.workspaceId),
    index().on(table.projectId, table.parentId),
    index().on(table.parentId),
    uniqueIndex().on(table.projectId, table.color).where(sql`${table.color} IS NOT NULL`),
  ],
);

export const tasks = pgTable(
  'tasks',
  {
    id: uuid().primaryKey(),
    workspaceId: uuid()
      .notNull()
      .references(() => workspaces.id, { onDelete: 'cascade' }),
    projectId: uuid()
      .notNull()
      .references(() => projects.id, { onDelete: 'cascade' }),
    /** From the project's counter, in the transaction that creates the task. Never reused. */
    number: integer().notNull(),
    title: text().notNull(),
    /** A BlockNote document. */
    description: jsonb().$type<Description>(),
    descriptionVersion: uuid(),
    // A status in use cannot be deleted. Purging a project removes both in one statement,
    // which the default (end of statement) check allows.
    statusId: uuid()
      .notNull()
      .references(() => statuses.id),
    priority: smallint().$type<Priority>().notNull(),
    position: text().notNull(),
    parentId: uuid().references((): AnyPgColumn => tasks.id, { onDelete: 'cascade' }),
    primaryTagId: uuid().references(() => tags.id, { onDelete: 'set null' }),
    closedAt: timestamp({ withTimezone: true }),
    deletedAt: timestamp({ withTimezone: true }),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (table) => [
    index().on(table.workspaceId),
    uniqueIndex().on(table.projectId, table.number),
    index().on(table.statusId),
    index().on(table.parentId),
    index().on(table.primaryTagId),
  ],
);

/**
 * The tasks' activity log (ADR 0006), written only by the server in the transaction of the
 * write it describes. An update's entry is also the record that its change id was applied,
 * which is how a resent update is recognised. `reordered` entries are kept for that alone and
 * are not synced.
 */
export const taskActivity = pgTable(
  'task_activity',
  {
    /** The task's id for its `created` entry, otherwise the update's change id. */
    id: uuid().primaryKey(),
    workspaceId: uuid()
      .notNull()
      .references(() => workspaces.id, { onDelete: 'cascade' }),
    projectId: uuid()
      .notNull()
      .references(() => projects.id, { onDelete: 'cascade' }),
    taskId: uuid()
      .notNull()
      .references(() => tasks.id, { onDelete: 'cascade' }),
    /** Who sent the write. Kept when the account is deleted, as the entry is the task's. */
    userId: text().references(() => user.id, { onDelete: 'set null' }),
    kind: text().$type<ActivityKind>().notNull(),
    changes: jsonb().$type<ActivityChange[]>().notNull(),
    createdAt: createdAt(),
  },
  (table) => [index().on(table.workspaceId), index().on(table.taskId)],
);

/**
 * Comments on tasks, written by devices through the outbox and applied in the order they
 * arrive. Not part of the log; the timeline merges the two.
 */
export const comments = pgTable(
  'comments',
  {
    id: uuid().primaryKey(),
    workspaceId: uuid()
      .notNull()
      .references(() => workspaces.id, { onDelete: 'cascade' }),
    projectId: uuid()
      .notNull()
      .references(() => projects.id, { onDelete: 'cascade' }),
    taskId: uuid()
      .notNull()
      .references(() => tasks.id, { onDelete: 'cascade' }),
    /** The author, the only one who can edit or delete it. Kept as null if the account goes. */
    userId: text().references(() => user.id, { onDelete: 'set null' }),
    /** A BlockNote document. */
    body: jsonb().$type<CommentBody>().notNull(),
    createdAt: createdAt(),
    editedAt: timestamp({ withTimezone: true }),
  },
  (table) => [index().on(table.workspaceId), index().on(table.taskId)],
);

/** One independent assignment per task and secondary tag. */
export const taskTags = pgTable(
  'task_tags',
  {
    taskId: uuid()
      .notNull()
      .references(() => tasks.id, { onDelete: 'cascade' }),
    tagId: uuid()
      .notNull()
      .references(() => tags.id, { onDelete: 'cascade' }),
    workspaceId: uuid()
      .notNull()
      .references(() => workspaces.id, { onDelete: 'cascade' }),
    projectId: uuid()
      .notNull()
      .references(() => projects.id, { onDelete: 'cascade' }),
  },
  (table) => [
    primaryKey({ columns: [table.taskId, table.tagId] }),
    index().on(table.workspaceId),
    index().on(table.projectId),
    index().on(table.tagId),
  ],
);
