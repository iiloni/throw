import { z } from 'zod';
import { colorSchema } from './colors';
import { positionSchema } from './position';
import { priorityNamesSchema } from './priorities';
import { newProjectStatusSchema, statusSetIssue } from './statuses';
import { timestampSchema } from './sync';

/**
 * A key the user can choose or the create form proposes: one to six characters, A to Z and
 * digits, starting with a letter.
 */
export const projectKeySchema = z.string().regex(/^[A-Z][A-Z0-9]{0,5}$/, 'Invalid project key');

/**
 * A key the server stored. When a proposal clashes the server appends a number (`CAT2`), which
 * can take it past the six characters a proposal may have.
 */
export const storedProjectKeySchema = z.string().regex(/^[A-Z][A-Z0-9]{0,11}$/);

export const projectSchema = z.object({
  /** UUIDv7 generated by the client, so a project can be made offline. */
  id: z.uuid(),
  workspaceId: z.uuid(),
  name: z.string().trim().min(1).max(80),
  /** Identifies the project's cards on the cross-project board. */
  color: colorSchema,
  /** The name of a bundled icon, shown in the navigation rail. */
  icon: z.string().min(1).max(40).nullable(),
  position: positionSchema,
  /**
   * The prefix of the project's task identifiers. Set by the server, so it is null on the
   * device until a project created there syncs (ADR 0007).
   */
  key: storedProjectKeySchema.nullable(),
  priorityNames: priorityNamesSchema,
  /** Set by the server while the project is in the trash. */
  deletedAt: timestampSchema.nullable(),
  /**
   * Device only, never synced: the key a project created on this device asks for. It travels
   * with the queued create, and the synced row replaces it.
   */
  proposedKey: projectKeySchema.optional(),
});
export type Project = z.infer<typeof projectSchema>;

/**
 * Creates a project with its first statuses in one request, so a project made offline can be
 * filled with tasks before it syncs. The server stores `key` or, when another project in the
 * workspace has it, the key with the smallest number from 2 up that is free.
 */
export const createProjectSchema = projectSchema
  .pick({ id: true, workspaceId: true, name: true, color: true, icon: true, position: true })
  .extend({
    key: projectKeySchema,
    priorityNames: priorityNamesSchema.optional(),
    statuses: z.array(newProjectStatusSchema).min(4).max(100),
  })
  .superRefine((project, context) => {
    const issue = statusSetIssue(project.statuses);
    if (issue) context.addIssue({ code: 'custom', message: issue, path: ['statuses'] });
    if (new Set(project.statuses.map((status) => status.id)).size !== project.statuses.length)
      context.addIssue({ code: 'custom', message: 'Duplicate status id', path: ['statuses'] });
  });
export type CreateProject = z.infer<typeof createProjectSchema>;

/**
 * Applied in the order writes arrive (ADR 0005 covers tasks only). A project stays in its
 * workspace: moving one would have to move everything under it. A key that another project
 * in the workspace has is refused. `trashed` moves the project to the trash or out of it;
 * the server stamps the time.
 */
export const updateProjectSchema = projectSchema
  .pick({ name: true, color: true, icon: true, position: true, priorityNames: true })
  .extend({ key: projectKeySchema, trashed: z.boolean() })
  .partial()
  .strict();
export type UpdateProject = z.infer<typeof updateProjectSchema>;

/**
 * The key the create form proposes for a name: the initials of a name of several words, or
 * the first three characters of a single word, in capitals. "P" when nothing fits.
 */
export function deriveProjectKey(name: string) {
  const words = name
    .normalize('NFKD')
    .replace(/\p{M}/gu, '')
    .toUpperCase()
    .split(/[^A-Z0-9]+/)
    .filter(Boolean);
  const candidate =
    words.length > 1
      ? words
          .map((word) => word[0])
          .join('')
          .slice(0, 6)
      : (words[0] ?? '').slice(0, 3);
  const key = candidate.replace(/^[0-9]+/, '');
  return projectKeySchema.safeParse(key).success ? key : 'P';
}

/** `key`, or `key` with the smallest number from 2 up that is not in `taken`. */
export function settleProjectKey(key: string, taken: ReadonlySet<string>) {
  if (!taken.has(key)) return key;
  for (let suffix = 2; ; suffix++) {
    const candidate = `${key}${suffix}`;
    if (!taken.has(candidate)) return candidate;
  }
}
