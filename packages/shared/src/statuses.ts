import { z } from 'zod';
import { positionSchema } from './position';

/**
 * Every status is filed under one of four fixed categories, which let the app compute
 * progress, hide closed work and put different projects on one board (docs/spec.md).
 */
export const STATUS_CATEGORIES = ['backlog', 'active', 'done', 'cancelled'] as const;
export const statusCategorySchema = z.enum(STATUS_CATEGORIES);
export type StatusCategory = z.infer<typeof statusCategorySchema>;

/** Done and cancelled statuses close a task; see `closedAtAfter`. */
export function isClosedCategory(category: StatusCategory) {
  return category === 'done' || category === 'cancelled';
}

/** A project's first statuses: one in each category, each its category's default. */
export const STARTER_STATUSES: readonly { name: string; category: StatusCategory }[] = [
  { name: 'Backlog', category: 'backlog' },
  { name: 'In progress', category: 'active' },
  { name: 'Done', category: 'done' },
  { name: 'Cancelled', category: 'cancelled' },
];

export const statusSchema = z.object({
  /** UUIDv7 generated by the client. */
  id: z.uuid(),
  workspaceId: z.uuid(),
  projectId: z.uuid(),
  name: z.string().trim().min(1).max(40),
  /** Fixed when the status is created: changing it would close or reopen its tasks at once. */
  category: statusCategorySchema,
  /** Fractional index among the statuses of the same category. */
  position: positionSchema,
  /** The status a task takes when it is dropped on the category. One per category. */
  isDefault: z.boolean(),
});
export type Status = z.infer<typeof statusSchema>;

/** A status as a new project's create request carries it. */
export const newProjectStatusSchema = statusSchema.omit({ workspaceId: true, projectId: true });
export type NewProjectStatus = z.infer<typeof newProjectStatusSchema>;

/** The server sets the workspace from the project. */
export const createStatusSchema = statusSchema.omit({ workspaceId: true });
export type CreateStatus = z.infer<typeof createStatusSchema>;

/**
 * Only `true` is accepted for `isDefault`: making a status the default clears the previous
 * one on the server, and a category is never left without one.
 */
export const updateStatusSchema = z
  .object({
    name: statusSchema.shape.name,
    position: positionSchema,
    isDefault: z.literal(true),
  })
  .partial()
  .strict();
export type UpdateStatus = z.infer<typeof updateStatusSchema>;

/** Orders statuses by category (backlog, active, done, cancelled), then by position. */
export function compareStatuses(
  a: Pick<Status, 'category' | 'position' | 'id'>,
  b: Pick<Status, 'category' | 'position' | 'id'>,
) {
  return (
    STATUS_CATEGORIES.indexOf(a.category) - STATUS_CATEGORIES.indexOf(b.category) ||
    (a.position < b.position ? -1 : a.position > b.position ? 1 : 0) ||
    (a.id < b.id ? -1 : a.id > b.id ? 1 : 0)
  );
}

/**
 * Whether a set of statuses keeps the rules a project's statuses always follow: at least one
 * in each category, and exactly one default in each.
 */
export function statusSetIssue(
  statuses: readonly Pick<Status, 'category' | 'isDefault'>[],
): string | null {
  for (const category of STATUS_CATEGORIES) {
    const inCategory = statuses.filter((status) => status.category === category);
    if (inCategory.length === 0) return `A project needs a ${category} status`;
    if (inCategory.filter((status) => status.isDefault).length !== 1)
      return `The ${category} category needs exactly one default status`;
  }
  return null;
}
