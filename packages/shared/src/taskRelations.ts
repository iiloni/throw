import { z } from 'zod';
import { isClosedCategory, type StatusCategory } from './statuses';
import { timestampSchema } from './sync';

/**
 * How two tasks of one workspace are related (docs/data-model.md, "Task relation"). One row
 * states a direction: its source `blocks` or `duplicates` its target. `relates_to` has none,
 * so its pair is stored in one order only (`canonicalPair`) and cannot be linked twice.
 * Relations are informational: they never stop a task from being moved, edited or closed.
 */
export const TASK_RELATION_KINDS = ['blocks', 'duplicates', 'relates_to'] as const;
export const taskRelationKindSchema = z.enum(TASK_RELATION_KINDS);
export type TaskRelationKind = z.infer<typeof taskRelationKindSchema>;

/** A relation as one of its tasks sees it. */
export const TASK_RELATION_ROLES = [
  'blocked_by',
  'blocks',
  'duplicates',
  'duplicated_by',
  'relates_to',
] as const;
export const taskRelationRoleSchema = z.enum(TASK_RELATION_ROLES);
export type TaskRelationRole = z.infer<typeof taskRelationRoleSchema>;

/** The groups of the task view, in its order. */
export const relationRoleLabel: Record<TaskRelationRole, string> = {
  blocked_by: 'Blocked by',
  blocks: 'Blocks',
  duplicates: 'Duplicates',
  duplicated_by: 'Duplicated by',
  relates_to: 'Relates to',
};

// Lower case, so ids compare as Postgres compares uuids.
const relationTaskId = z.uuid().transform((id) => id.toLowerCase());

export const taskRelationSchema = z.object({
  /** UUIDv7 generated by the client, so a relation can be made offline. */
  id: z.uuid(),
  workspaceId: z.uuid(),
  sourceTaskId: z.uuid(),
  targetTaskId: z.uuid(),
  kind: taskRelationKindSchema,
  /** A server time; a placeholder from the device's clock until the row syncs. */
  createdAt: timestampSchema,
});
export type TaskRelation = z.infer<typeof taskRelationSchema>;

/**
 * Linking two tasks. The server sets the workspace from the tasks and stores a `relates_to`
 * pair in canonical order whichever order it was sent in.
 */
export const createTaskRelationSchema = z
  .strictObject({
    id: z.uuid(),
    sourceTaskId: relationTaskId,
    targetTaskId: relationTaskId,
    kind: taskRelationKindSchema,
  })
  .refine((body) => body.sourceTaskId !== body.targetTaskId, 'A task cannot relate to itself')
  .transform((body) => ({ ...body, ...canonicalPair(body) }));
export type CreateTaskRelation = z.input<typeof createTaskRelationSchema>;

/** The stored order of a pair: as given, except that `relates_to` puts the lower id first. */
export function canonicalPair({
  sourceTaskId,
  targetTaskId,
  kind,
}: Pick<TaskRelation, 'sourceTaskId' | 'targetTaskId' | 'kind'>) {
  return kind === 'relates_to' && targetTaskId < sourceTaskId
    ? { sourceTaskId: targetTaskId, targetTaskId: sourceTaskId }
    : { sourceTaskId, targetTaskId };
}

/** The relation as `taskId` sees it, or null when it does not involve that task. */
export function relationRole(
  relation: Pick<TaskRelation, 'sourceTaskId' | 'targetTaskId' | 'kind'>,
  taskId: string,
): { role: TaskRelationRole; otherTaskId: string } | null {
  const outgoing = relation.sourceTaskId === taskId;
  if (!outgoing && relation.targetTaskId !== taskId) return null;
  const otherTaskId = outgoing ? relation.targetTaskId : relation.sourceTaskId;
  const role: TaskRelationRole =
    relation.kind === 'relates_to'
      ? 'relates_to'
      : relation.kind === 'blocks'
        ? outgoing
          ? 'blocks'
          : 'blocked_by'
        : outgoing
          ? 'duplicates'
          : 'duplicated_by';
  return { role, otherTaskId };
}

/**
 * The row that says `taskId` has `role` towards `otherTaskId`: “Blocked by” is the other task
 * blocking this one, and “Duplicated by” the other task duplicating it.
 */
export function relationFromRole(taskId: string, role: TaskRelationRole, otherTaskId: string) {
  const swapped = role === 'blocked_by' || role === 'duplicated_by';
  const kind: TaskRelationKind =
    role === 'blocks' || role === 'blocked_by'
      ? 'blocks'
      : role === 'relates_to'
        ? 'relates_to'
        : 'duplicates';
  const sourceTaskId = (swapped ? otherTaskId : taskId).toLowerCase();
  const targetTaskId = (swapped ? taskId : otherTaskId).toLowerCase();
  return { kind, ...canonicalPair({ sourceTaskId, targetTaskId, kind }) };
}

/**
 * Why a relation cannot be added beside `existing`: a task linked to itself, the same link
 * again, or the reverse of a directed one (B blocks A refuses A blocks B, and likewise for
 * duplicates). Null when it can.
 */
export function relationConflict(
  existing: readonly Pick<TaskRelation, 'sourceTaskId' | 'targetTaskId' | 'kind'>[],
  candidate: Pick<TaskRelation, 'sourceTaskId' | 'targetTaskId' | 'kind'>,
): 'self' | 'exists' | 'reverse' | null {
  const { sourceTaskId, targetTaskId } = canonicalPair(candidate);
  if (sourceTaskId === targetTaskId) return 'self';
  for (const row of existing) {
    if (row.kind !== candidate.kind) continue;
    if (row.sourceTaskId === sourceTaskId && row.targetTaskId === targetTaskId) return 'exists';
    if (
      candidate.kind !== 'relates_to' &&
      row.sourceTaskId === targetTaskId &&
      row.targetTaskId === sourceTaskId
    )
      return 'reverse';
  }
  return null;
}

export const relationConflictMessage = {
  self: 'A task cannot relate to itself',
  exists: 'These tasks are already linked this way',
  reverse: 'The other task already has the reverse relation',
} as const;

/**
 * The tasks that still block `taskId`: sources of its `blocks` relations that are neither
 * closed nor in the trash. A blocker the device does not hold (purged, or not synced yet)
 * does not count.
 */
export function openBlockers<T>(
  taskId: string,
  relations: readonly Pick<TaskRelation, 'sourceTaskId' | 'targetTaskId' | 'kind'>[],
  blocker: (id: string) => { task: T; category: StatusCategory; trashed: boolean } | undefined,
): T[] {
  return relations.flatMap((relation) => {
    if (relation.kind !== 'blocks' || relation.targetTaskId !== taskId) return [];
    const found = blocker(relation.sourceTaskId);
    return found && !found.trashed && !isClosedCategory(found.category) ? [found.task] : [];
  });
}
