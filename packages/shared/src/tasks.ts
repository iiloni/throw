import { z } from 'zod';
import { comparePositions, positionSchema } from './position';
import { DEFAULT_PRIORITY, prioritySchema } from './priorities';
import { isClosedCategory, type StatusCategory } from './statuses';
import { timestampSchema, txidResponseSchema } from './sync';

/** A BlockNote document, text only. Null for a task without a description. */
export const descriptionSchema = z.array(z.record(z.string(), z.unknown())).nullable();
export type Description = z.infer<typeof descriptionSchema>;

export const taskTitleSchema = z.string().trim().max(500);

/** A task, or a subtask when it has a parent (docs/data-model.md). */
export const taskSchema = z.object({
  /** UUIDv7 generated by the client, so a task can be made offline. */
  id: z.uuid(),
  workspaceId: z.uuid(),
  /** A task stays in its project (ADR 0007). */
  projectId: z.uuid(),
  /** Assigned by the server; null on the device until a task created there syncs. */
  number: z.number().int().positive().nullable(),
  title: taskTitleSchema,
  description: descriptionSchema,
  /** A UUIDv7 named by each description save, used only to detect conflicts (ADR 0005). */
  descriptionVersion: z.uuid().nullable(),
  statusId: z.uuid(),
  priority: prioritySchema,
  /** Within its status and priority, or for a subtask within its parent. */
  position: positionSchema,
  parentId: z.uuid().nullable(),
  /** Server times. A device holds a placeholder from its own clock until the row syncs. */
  closedAt: timestampSchema.nullable(),
  deletedAt: timestampSchema.nullable(),
  createdAt: timestampSchema,
});
export type Task = z.infer<typeof taskSchema>;

/**
 * Creating a task. The server sets the workspace from the project, assigns the number and
 * stamps the times. Without a status, or with one that no longer exists, the task takes the
 * project's backlog default.
 */
export const createTaskSchema = taskSchema
  .pick({
    id: true,
    projectId: true,
    title: true,
    description: true,
    descriptionVersion: true,
    position: true,
    parentId: true,
  })
  .extend({
    statusId: z.uuid().nullable().default(null),
    priority: prioritySchema.default(DEFAULT_PRIORITY),
  })
  .strict();
export type CreateTask = z.input<typeof createTaskSchema>;

/** The task fields a write can be refused on, and the activity log records. */
export const TASK_FIELDS = [
  'title',
  'description',
  'statusId',
  'priority',
  'parentId',
  'trashed',
] as const;
export const taskFieldSchema = z.enum(TASK_FIELDS);
export type TaskField = z.infer<typeof taskFieldSchema>;

const change = <T extends z.ZodType>(value: T) =>
  z.object({ before: value, after: value }).strict();

/**
 * The fields one update changes, each with the value the device held before the change and
 * the value it wants (ADR 0005). The server applies a field only when its value is still the
 * one the device saw. A description is compared by its version, and a position applies only
 * when, after the rest of the write, the task is in the status, priority and parent the
 * position was computed for.
 */
export const taskChangesSchema = z
  .object({
    title: change(taskTitleSchema),
    priority: change(prioritySchema),
    statusId: change(z.uuid()),
    parentId: change(z.uuid().nullable()),
    trashed: change(z.boolean()),
    description: z
      .object({
        before: z.uuid().nullable(),
        after: z.object({ version: z.uuid(), document: descriptionSchema }).strict(),
      })
      .strict(),
    position: z
      .object({
        after: positionSchema,
        statusId: z.uuid(),
        priority: prioritySchema,
        parentId: z.uuid().nullable(),
      })
      .strict(),
  })
  .partial()
  .strict()
  .refine((changes) => Object.keys(changes).length > 0, 'An update changes something');
export type TaskChanges = z.infer<typeof taskChangesSchema>;

export const updateTaskSchema = z
  .object({
    /**
     * A UUIDv7 for this change to this task. It becomes the id of the change's activity entry,
     * and a resent request with a change id the server has recorded does nothing.
     */
    changeId: z.uuid(),
    changes: taskChangesSchema,
  })
  .strict();
export type UpdateTask = z.infer<typeof updateTaskSchema>;

/**
 * Why a field was not applied: something else changed it first (`stale`), or the value is no
 * longer possible (`invalid`), such as a status deleted meanwhile.
 */
export const refusalReasonSchema = z.enum(['stale', 'invalid']);
export type RefusalReason = z.infer<typeof refusalReasonSchema>;

export const refusedFieldSchema = z.object({ field: taskFieldSchema, reason: refusalReasonSchema });
export type RefusedField = z.infer<typeof refusedFieldSchema>;

/**
 * An update always succeeds; the fields it could not apply are listed. `txid` is null when the
 * task row did not change, so the client has nothing to wait for.
 */
export const updateTaskResponseSchema = txidResponseSchema.extend({
  refused: z.array(refusedFieldSchema),
});
export type UpdateTaskResponse = z.infer<typeof updateTaskResponseSchema>;

/** `CAT-12`, or null until both the project's key and the task's number have synced. */
export function taskIdentifier(project: { key: string | null }, task: { number: number | null }) {
  return project.key !== null && task.number !== null ? `${project.key}-${task.number}` : null;
}

/**
 * The order of a board column: by priority (1 first), then position, then id, which breaks
 * the tie when two devices handed out the same position.
 */
export function compareTasks(
  a: Pick<Task, 'priority' | 'position' | 'id'>,
  b: Pick<Task, 'priority' | 'position' | 'id'>,
) {
  return (
    a.priority - b.priority ||
    comparePositions(a.position, b.position) ||
    (a.id < b.id ? -1 : a.id > b.id ? 1 : 0)
  );
}

/** The closed zone's order: most recently closed first. */
export function compareClosedTasks(
  a: Pick<Task, 'closedAt' | 'id'>,
  b: Pick<Task, 'closedAt' | 'id'>,
) {
  const at = a.closedAt ?? '';
  const bt = b.closedAt ?? '';
  return at < bt ? 1 : at > bt ? -1 : a.id < b.id ? 1 : a.id > b.id ? -1 : 0;
}

/**
 * A task counts as trashed when it, its parent or its project is in the trash. Trashing a
 * parent or project writes nothing to the rows under it.
 */
export function isTaskTrashed(
  task: Pick<Task, 'deletedAt'>,
  parent: Pick<Task, 'deletedAt'> | null | undefined,
  project: { deletedAt: string | null } | null | undefined,
) {
  return task.deletedAt !== null || !!parent?.deletedAt || !!project?.deletedAt;
}

/**
 * `closedAt` after a task moves from a status in `from` to one in `to`: stamped with `now`
 * when it enters a done or cancelled status from an open one, cleared when it reopens, kept
 * between two closed statuses. `from` is null for a new task.
 */
export function closedAtAfter(
  closedAt: string | null,
  from: StatusCategory | null,
  to: StatusCategory,
  now: string,
) {
  if (!isClosedCategory(to)) return null;
  return from !== null && isClosedCategory(from) ? closedAt : now;
}
